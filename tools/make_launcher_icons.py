#!/usr/bin/env python3
"""Generates the app-lock disguise launcher icons (adaptive icons) into app/src/main/res.

Each disguise has several styles; style N of a disguise is the activity-alias
`.launcher.<Disguise>` (N = 1) or `.launcher.<Disguise><N>`, using
`@mipmap/ic_launcher_<disguise>[N]`. Glyphs are Material Symbols Rounded (Apache 2.0).

Usage: python3 tools/make_launcher_icons.py
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from import_icons import fetch  # noqa: E402

RES = Path(__file__).resolve().parent.parent / "app/src/main/res"

# disguise -> styles of (glyph, background, glyph color). Order matters: it is the style index.
STYLES = {
    "calculator": [("calculate", "#FF37474F", "#FFFFFFFF"), ("functions", "#FFFF8F00", "#FFFFFFFF"), ("percent", "#FFFFFFFF", "#FF2E7D32")],
    "clock": [("schedule", "#FF1A237E", "#FFFFFFFF"), ("alarm", "#FFFFFFFF", "#FFE53935"), ("timer", "#FF263238", "#FF80DEEA")],
    "calendar": [("calendar_month", "#FF1E88E5", "#FFFFFFFF"), ("event", "#FFFFFFFF", "#FF1E88E5"), ("today", "#FFE53935", "#FFFFFFFF")],
    "notes": [("sticky_note_2", "#FFFBC02D", "#FF3E2723"), ("edit_note", "#FFFFFFFF", "#FFF9A825"), ("description", "#FF43A047", "#FFFFFFFF")],
}

FOREGROUND = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "{glyph}" (Apache 2.0) in the 66dp safe zone. Generated by tools/make_launcher_icons.py; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="0.06"
        android:scaleY="0.06"
        android:translateX="25.2"
        android:translateY="82.8">
{paths}
    </group>
</vector>
"""

BACKGROUND = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_launcher_icons.py; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="{color}" android:pathData="M0,0h108v108h-108z" />
</vector>
"""

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_launcher_icons.py; do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/{name}_background" />
    <foreground android:drawable="@drawable/{name}_foreground" />
    <monochrome android:drawable="@drawable/{name}_foreground" />
</adaptive-icon>
"""


def main() -> int:
    for disguise, styles in STYLES.items():
        for index, (glyph, background, color) in enumerate(styles, start=1):
            name = f"ic_launcher_{disguise}" + ("" if index == 1 else str(index))
            paths = re.findall(r'<path d="([^"]+)"', fetch(glyph, filled=False))
            body = "\n".join(f'        <path\n            android:fillColor="{color}"\n            android:pathData="{d}" />' for d in paths)
            (RES / "drawable" / f"{name}_foreground.xml").write_text(FOREGROUND.format(glyph=glyph, paths=body))
            (RES / "drawable" / f"{name}_background.xml").write_text(BACKGROUND.format(color=background))
            for suffix in ("", "_round"):
                (RES / "mipmap-anydpi" / f"{name}{suffix}.xml").write_text(ADAPTIVE.format(name=name))
            print("wrote", name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
