#!/usr/bin/env python3
"""Imports Material Symbols (Apache 2.0) as Android vector drawables into core:designsystem.

Usage: python3 tools/import_icons.py
Add a name to ICONS (optionally ":fill" for the filled style) and rerun.
"""
import re
import sys
import urllib.request
from pathlib import Path

ICONS = [
    "videocam", "videocam:fill", "videocam_off", "grid_view", "smartphone", "qr_code_2",
    "qr_code_scanner", "share", "battery_full", "battery_charging_full", "battery_alert", "wifi",
    "vpn_lock", "cameraswitch", "volume_up", "volume_off", "group", "delete", "logout", "shield:fill",
    "bolt", "chevron_right", "check_circle:fill", "error:fill", "cloud_off", "content_copy", "mic",
    "visibility", "devices", "add", "arrow_back", "lock", "settings", "hd", "fullscreen", "link",
    "screen_rotation", "notifications_active", "alarm:fill", "folder_open", "computer", "battery_2_bar",
    "zoom_in", "visibility_off", "upload",
    "palette", "contrast", "bedtime", "flashlight_on", "flashlight_off",
    "calculate", "schedule", "calendar_month", "sticky_note_2", "backspace", "alarm_add", "chevron_left", "dialpad", "keyboard", "language", "edit", "view_agenda", "view_quilt",
]
BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web"
OUT = Path(__file__).resolve().parent.parent / "core/designsystem/src/main/res/drawable"

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "{name}" (Apache 2.0). Generated by tools/import_icons.py; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
{paths}
    </group>
</vector>
"""


def fetch(name: str, filled: bool) -> str:
    suffix = "_fill1" if filled else ""
    url = f"{BASE}/{name}/materialsymbolsrounded/{name}{suffix}_24px.svg"
    with urllib.request.urlopen(url, timeout=20) as response:
        return response.read().decode()


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    failures = []
    for entry in ICONS:
        name, _, style = entry.partition(":")
        filled = style == "fill"
        try:
            svg = fetch(name, filled)
        except Exception as error:  # noqa: BLE001 - report every missing icon at the end
            failures.append(f"{entry}: {error}")
            continue
        paths = re.findall(r'<path d="([^"]+)"', svg)
        if not paths:
            failures.append(f"{entry}: no <path> found")
            continue
        body = "\n".join(
            f'        <path android:fillColor="#FF000000" android:pathData="{d}" />' for d in paths
        )
        file_name = f"cn_ic_{name}{'_filled' if filled else ''}.xml"
        (OUT / file_name).write_text(TEMPLATE.format(name=entry, paths=body))
    for failure in failures:
        print("FAILED", failure, file=sys.stderr)
    print(f"imported {len(ICONS) - len(failures)}/{len(ICONS)} icons into {OUT}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
